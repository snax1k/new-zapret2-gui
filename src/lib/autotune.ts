import { AutotuneRow } from '../types';

/**
 * Вывод по итогам автоподбора.
 *
 * Один и тот же вывод нужен в двух местах — в окне подбора и в мастере
 * первого запуска, — и расходиться они не должны: если окно говорит
 * «подошло», а мастер «ничего не нашлось», человек перестаёт верить обоим.
 * Поэтому логика живёт здесь, а не в компонентах.
 *
 * - `not-needed` — цели открылись без обхода, блокировки нет;
 * - `found` — есть вариант, прошедший все пробы;
 * - `partial` — лучший вариант проходит через раз;
 * - `none` — не помог ни один;
 * - `empty` — проверка остановлена раньше, чем что-то выяснилось.
 */
export type AutotuneVerdictKind = 'not-needed' | 'found' | 'partial' | 'none' | 'empty';

export interface AutotuneSummary {
  kind: AutotuneVerdictKind;
  /** Лучший вариант — для found и partial. */
  best?: AutotuneRow;
  /** Все сработавшие варианты, лучший первым. */
  winners: AutotuneRow[];
  /** Сколько вариантов уже проверено. */
  done: number;
  /** Сколько всего в очереди, включая эталон. */
  total: number;
}

export const summarizeAutotune = (rows: AutotuneRow[]): AutotuneSummary => {
  const finished = rows.filter(r => r.phase === 'done');
  // Эталон — не стратегия, применять его нельзя: это ответ на вопрос
  // «а блокируют ли вообще».
  const baseline = rows.find(r => r.id === 'off');
  const strategies = finished.filter(r => r.id !== 'off');

  // Ранжирование по числу успешных проб, а НЕ по времени.
  //
  // Когда-то здесь стояло sort((a, b) => a.ms - b.ms), и побеждал самый
  // быстрый. Это неверно в корне: быстрый ответ часто означает быстрый
  // отказ. На живом замере блокировка отвечала за 38 мс сбросом, а
  // успешное соединение занимало 300 мс. Время — только разделитель при
  // равном счёте.
  const winners = strategies
    .filter(r => r.passed > 0)
    .sort((a, b) => (b.passed - a.passed) || (a.ms - b.ms));

  const best = winners[0];
  const base = { winners, done: finished.length, total: rows.length };

  if (baseline && baseline.phase === 'done' && baseline.ok) return { ...base, kind: 'not-needed' };
  if (best && best.ok) return { ...base, kind: 'found', best };
  if (best) return { ...base, kind: 'partial', best };
  // «Не помог ни один» можно сказать, только если варианты действительно
  // проверялись. Остановленная на эталоне проверка ничего не доказывает.
  if (strategies.length === 0) return { ...base, kind: 'empty' };
  return { ...base, kind: 'none' };
};

